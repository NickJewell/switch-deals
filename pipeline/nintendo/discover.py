"""Phase 0 discovery: writes docs/data-dictionary.md, docs/manual-check.md and test fixtures.

Run: `make discover`. Uses the on-disk cache, so re-runs are cheap.
"""

from __future__ import annotations

import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from pipeline.http import CachedClient
from pipeline.models import fmt_gbp, to_pence
from pipeline.nintendo.catalog import UNRANKED, CatalogClient, doc_to_title
from pipeline.nintendo.prices import PriceClient

DOCS = Path("docs")
FIXTURES = Path("tests/fixtures")


def _type(v: object) -> str:
    if isinstance(v, list):
        return f"list[{_type(v[0])}]" if v else "list"
    return type(v).__name__


def _sample(v: object) -> str:
    s = json.dumps(v, ensure_ascii=False)
    s = s if len(s) <= 60 else s[:57] + "…"
    return s.replace("|", "\\|")


def field_table(docs: list[dict]) -> list[str]:
    fill: Counter[str] = Counter()
    types: dict[str, str] = {}
    samples: dict[str, list[str]] = {}
    for d in docs:
        for k, v in d.items():
            if v in (None, "", []):
                continue
            fill[k] += 1
            types.setdefault(k, _type(v))
            s = samples.setdefault(k, [])
            if len(s) < 2 and _sample(v) not in s:
                s.append(_sample(v))
    rows = ["| field | filled | type | samples |", "|---|---:|---|---|"]
    for k, n in sorted(fill.items(), key=lambda kv: (-kv[1], kv[0])):
        rows.append(
            f"| `{k}` | {100 * n / len(docs):.0f}% | {types[k]} | {' · '.join(samples[k])} |"
        )
    return rows


def main() -> None:
    http = CachedClient()
    cat = CatalogClient(http)
    prices = PriceClient(http)

    sample = cat.search([], start=0, rows=1000)
    all_games, sample_docs = sample["numFound"], sample["docs"]
    on = list(cat.iter_docs(["price_has_discount_b:true"]))
    n = len(on)

    # --- nsuids
    nsuid_counts = Counter(len(d.get("nsuid_txt") or []) for d in on)
    prefixes = Counter(x[:4] for d in on for x in d.get("nsuid_txt") or [])
    only_prefix = Counter((d["nsuid_txt"][0][:4]) for d in on if len(d.get("nsuid_txt") or []) == 1)

    # --- Switch 2 cross-tab
    def sig(d: dict) -> tuple:
        codes = sorted({c.strip()[:3] for c in d.get("product_code_txt") or [] if c.strip()})
        return (
            ",".join(d.get("playable_on_txt") or []) or "∅",
            d.get("originally_for_t") or "∅",
            ",".join(d.get("system_names_txt") or []) or "∅",
            ",".join(codes) or "∅",
        )

    xtab = Counter(sig(d) for d in on)
    s2 = [d for d in on if doc_to_title(d).is_switch2]

    # --- popularity
    ranked = [d for d in on if d.get("downloads_rank_i") not in (None, UNRANKED)]
    top = sorted(ranked, key=lambda d: d["downloads_rank_i"])[:8]
    hits = Counter(d.get("hits_i") for d in on)

    # --- index vs API (single-nsuid docs so the comparison is clean)
    single = [d for d in on if len(d.get("nsuid_txt") or []) == 1]
    cmp_docs = sorted(single, key=lambda d: d.get("downloads_rank_i", UNRANKED))[:50]
    api = {p.nsuid: p for p, _ in prices.get([d["nsuid_txt"][0] for d in cmp_docs], "GB")}
    reg_ok = sale_ok = api_no_disc = 0
    mismatches = []
    for d in cmp_docs:
        p = api.get(d["nsuid_txt"][0])
        if p is None or p.regular_p is None:
            mismatches.append(f"{d['title']}: missing from API")
            continue
        reg_ok += to_pence(d.get("price_regular_f")) == p.regular_p
        if p.sale_p is None:
            api_no_disc += 1
            mismatches.append(f"{d['title']}: index says on sale, API has no discount (stale)")
        elif to_pence(d.get("price_discounted_f")) == p.sale_p:
            sale_ok += 1
        else:
            mismatches.append(
                f"{d['title']}: index {d.get('price_discounted_f')} vs API {fmt_gbp(p.sale_p)}"
            )
    currencies = Counter(p.currency for p in api.values())

    # --- multi-nsuid example
    multi = [d for d in on if len(d.get("nsuid_txt") or []) > 1]

    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    out: list[str] = [
        "# Nintendo data dictionary",
        "",
        f"_Generated by `make discover` on {now}. Unofficial endpoints: re-run if things break._",
        "",
        "## Endpoints",
        "- Catalogue (Solr): `https://searching.nintendo-europe.com/en/select` "
        "(`q=*&fq=type:GAME`, page with `start`/`rows`; **`rows=1000` is accepted**; "
        "stable paging needs `sort=fs_id asc`).",
        "- Prices: `https://api.ec.nintendo.com/v1/price?country=GB&lang=en&ids=…` (≤50 ids).",
        "",
        "## Headline findings",
        f"- `type:GAME` docs: **{all_games:,}**. On sale (`price_has_discount_b:true`): **{n:,}**.",
        f"- **`/en/` index prices are GBP.** Price API currencies: {dict(currencies)}. "
        f"For 50 most-downloaded single-nsuid on-sale titles: regular price matches "
        f"{reg_ok}/50, sale price matches {sale_ok}/50, {api_no_disc} index-says-sale-but-API-"
        "doesn't (index lags). → **Price API is the only source for spoken/on-screen prices.**",
        '- API `raw_value` is a string without trailing zeros (`"7.2"`) — parse with Decimal '
        "into integer pence.",
        "- **Price fields:** `price_regular_f`, `price_discounted_f`, "
        "`price_discount_percentage_f`, **`price_lowest_f` (lowest-ever)**, `price_sorting_f`. "
        f"`price_lowest_f` null rate on sale docs: "
        f"{sum('price_lowest_f' not in d for d in on)}/{n}.",
        "- **Index price fields can mix nsuids.** e.g. FINAL FANTASY VII REBIRTH carries "
        "`70010000112478` (GB £49.99→£7.49) and `70070000032076` (£64.99→£9.74); the doc shows "
        "regular 64.99 / discounted 9.74 / lowest 7.49. Treat them as hints only.",
        f"- **`nsuid_txt` is a list.** Count per on-sale doc: {dict(sorted(nsuid_counts.items()))}. "
        f"Prefixes: {dict(prefixes)}. When a doc has one nsuid, its prefix: {dict(only_prefix)}.",
        "  - `7001…` = base game application, `7007…` = bundle / edition "
        "(e.g. complete editions, multi-game bundles), `7005…` = add-on (only seen alongside "
        "others). Primary nsuid rule: lowest `7001…`, else lowest id.",
        f"  - {nsuid_counts.get(0, 0)} on-sale docs have no nsuid at all → cannot be priced; "
        "skipped.",
        "- **No `popularity` field exists.** `hits_i` is constant "
        f"({dict(hits.most_common(3))}) → useless. Use **`downloads_rank_i`: lower = more "
        f"popular, 999999 = unranked.** Ranked on-sale docs: {len(ranked)}/{n}. Top by rank: "
        + ", ".join(f"{d['title']} ({d['downloads_rank_i']})" for d in top)
        + ".",
        "",
        "## Switch 2 detection — proposed rule (Nick to confirm)",
        "`is_switch2 = 'BEE' in playable_on_txt or 'Nintendo Switch 2' in system_names_txt`",
        "",
        f"Cross-tab over {n} on-sale docs (playable_on · originally_for · system_names · "
        "product-code prefixes):",
        "",
        "| count | playable_on_txt | originally_for_t | system_names_txt | product_code prefix |",
        "|---:|---|---|---|---|",
        *[f"| {v} | {k[0]} | {k[1]} | {k[2]} | {k[3]} |" for k, v in xtab.most_common()],
        "",
        "- The three platform fields agree on every doc. Product codes are often blank "
        "(`∅`) or wrong-prefixed, so **don't use product codes**.",
        f'- {len(s2)} on-sale Switch 2 docs. "Nintendo Switch 2 Edition" releases are their own '
        "BEE docs. Switch 1 games that merely run on Switch 2 stay `HAC` (not flagged).",
        "",
        "## Multi-nsuid examples",
        "",
        "| title | nsuids | idx regular | idx sale | idx lowest |",
        "|---|---|---:|---:|---:|",
        *[
            f"| {d['title']} | {', '.join(d['nsuid_txt'])} | {d.get('price_regular_f')} | "
            f"{d.get('price_discounted_f')} | {d.get('price_lowest_f')} |"
            for d in multi[:8]
        ],
        "",
        "## Index vs API mismatches (top-50 sample)",
        *([f"- {m}" for m in mismatches] or ["- none"]),
        "",
        f"## All fields — `type:GAME` sample (first 1,000 by fs_id of {all_games:,})",
        "",
        *field_table(sample_docs),
        "",
        f"## All fields — on-sale docs ({n:,})",
        "",
        *field_table(on),
        "",
    ]
    DOCS.mkdir(exist_ok=True)
    (DOCS / "data-dictionary.md").write_text("\n".join(out))

    # --- manual check: 10 well-known single-nsuid titles, mix of S2/Switch + deep/shallow
    pool = [d for d in single if d["nsuid_txt"][0].startswith("7001") and d in ranked]
    pool.sort(key=lambda d: d["downloads_rank_i"])
    pool = pool[:250]
    live = {p.nsuid for p, _ in prices.get([d["nsuid_txt"][0] for d in pool], "GB") if p.on_sale}
    pool = [d for d in pool if d["nsuid_txt"][0] in live]  # API-confirmed sales only
    picks: list[dict] = []
    for want_s2, want_deep, k in [
        (True, True, 3),
        (True, False, 2),
        (False, True, 3),
        (False, False, 2),
    ]:
        cand = [
            d
            for d in pool
            if doc_to_title(d).is_switch2 == want_s2
            and ((d.get("price_discount_percentage_f") or 0) >= 50) == want_deep
            and d not in picks
        ]
        picks += cand[:k]
    chk = {p.nsuid: p for p, _ in prices.get([d["nsuid_txt"][0] for d in picks], "GB")}
    rows = [
        "# Manual price check vs nintendo.co.uk",
        "",
        f"_Generated {now}. Open each link, fill in the site prices, tick if they match._",
        "",
        "| # | title | S2 | API regular | API sale | ends (UTC) | site regular | site sale | ok? |",
        "|---:|---|:-:|---:|---:|---|---|---|:-:|",
    ]
    for i, d in enumerate(picks, 1):
        t, p = doc_to_title(d), chk.get(d["nsuid_txt"][0])
        end = p.sale_end.strftime("%Y-%m-%d %H:%M") if p and p.sale_end else "—"
        rows.append(
            f"| {i} | [{t.title}]({t.url}) | {'✓' if t.is_switch2 else ''} | "
            f"{fmt_gbp(p and p.regular_p)} | {fmt_gbp(p and p.sale_p)} | {end} |  |  |  |"
        )
    (DOCS / "manual-check.md").write_text("\n".join(rows) + "\n")

    # --- fixtures: a trimmed Solr page + matching price response
    fx = [d for d in multi if d["title"].startswith("FINAL FANTASY VII REBIRTH")][:1]
    fx += [d for d in on if not d.get("nsuid_txt")][:1]
    fx += [d for d in picks[:3]]
    keep = {
        "fs_id", "title", "nsuid_txt", "playable_on_txt", "system_names_txt", "originally_for_t",
        "product_code_txt", "publisher", "developer", "pretty_game_categories_txt",
        "dates_released_dts", "downloads_rank_i", "price_regular_f", "price_discounted_f",
        "price_lowest_f", "price_discount_percentage_f", "price_has_discount_b",
        "image_url_sq_s", "image_url_h16x9_s", "url", "excerpt",
    }  # fmt: skip
    fx = [{k: v for k, v in d.items() if k in keep} for d in fx]
    FIXTURES.mkdir(parents=True, exist_ok=True)
    (FIXTURES / "solr_page.json").write_text(
        json.dumps({"response": {"numFound": len(fx), "start": 0, "docs": fx}}, indent=1)
    )
    ids = sorted({x for d in fx for x in d.get("nsuid_txt") or []})
    url = http.build_url(
        "https://api.ec.nintendo.com/v1/price",
        [("country", "GB"), ("lang", "en"), ("ids", ",".join(ids))],
    )
    (FIXTURES / "prices_gb.json").write_text(
        json.dumps(http.get_json(url, ttl=3600).data, indent=1)
    )

    print(f"on-sale docs={n}  switch2={len(s2)}  network calls={http.network_calls}")
    print("wrote docs/data-dictionary.md, docs/manual-check.md, tests/fixtures/*.json")


if __name__ == "__main__":
    main()
